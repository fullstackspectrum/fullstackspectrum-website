#!/usr/bin/env python3
"""Rebuild assets/js/posts.js from the posts in blog/.

Each blog/*.html file is the source of truth for its own listing:
  title    the <h1>
  date     <time datetime="YYYY-MM-DD"> in the article meta line
  excerpt  <meta name="description">

Skipped: blog/index.html, files starting with "_" (the template), and any post
with <meta name="robots" content="noindex"> (hidden / unlisted).

Posts hosted elsewhere live in blog/external-posts.json.

Usage:
  python3 scripts/build_posts.py          rewrite posts.js
  python3 scripts/build_posts.py --check  exit 1 if posts.js is out of date
"""
import html
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BLOG = ROOT / "blog"
EXTERNAL = BLOG / "external-posts.json"
OUTPUT = ROOT / "assets" / "js" / "posts.js"

HEADER = """\
/*
 * Blog post index — the single list both the homepage and /blog/ read from.
 *
 * GENERATED by scripts/build_posts.py — do not edit by hand.
 * It is rebuilt automatically when changes to blog/ are merged into main.
 *
 * To add a post: python3 scripts/new_post.py <slug> "<title>"
 * To hide a post: add <meta name="robots" content="noindex"> to its <head>.
 * To link a post hosted elsewhere: add it to blog/external-posts.json.
 */
"""

H1 = re.compile(r"<h1[^>]*>(.*?)</h1>", re.S | re.I)
DATE = re.compile(r'<time[^>]*datetime="(\d{4}-\d{2}-\d{2})"', re.I)
DESCRIPTION = re.compile(r'<meta\s+name="description"\s+content="([^"]*)"', re.I)
NOINDEX = re.compile(r'<meta\s+name="robots"\s+content="[^"]*noindex', re.I)
TAG = re.compile(r"<[^>]+>")
TEMPLATE_PLACEHOLDERS = ("POST TITLE", "POST DESCRIPTION", "SLUG")


def text(fragment):
    return " ".join(html.unescape(TAG.sub("", fragment)).split())


def read_post(path):
    """Return the post's listing entry, None if hidden, or raise if incomplete."""
    source = path.read_text(encoding="utf-8")
    if NOINDEX.search(source):
        return None

    h1, date, desc = H1.search(source), DATE.search(source), DESCRIPTION.search(source)
    missing = [name for name, m in (("<h1>", h1), ('<time datetime="...">', date),
                                    ('<meta name="description">', desc)) if not m]
    if missing:
        raise ValueError(f"{path.relative_to(ROOT)}: missing {', '.join(missing)}")
    leftovers = [p for p in TEMPLATE_PLACEHOLDERS if p in source]
    if leftovers:
        raise ValueError(f"{path.relative_to(ROOT)}: still has template placeholder(s) {', '.join(leftovers)}")

    return {
        "title": text(h1.group(1)),
        "date": date.group(1),
        "excerpt": html.unescape(desc.group(1)).strip(),
        "url": f"/blog/{path.name}",
    }


def collect():
    posts, errors = [], []
    for path in sorted(BLOG.glob("*.html")):
        if path.name == "index.html" or path.name.startswith("_"):
            continue
        try:
            post = read_post(path)
        except ValueError as e:
            errors.append(str(e))
            continue
        if post:
            posts.append(post)

    if EXTERNAL.exists():
        for post in json.loads(EXTERNAL.read_text(encoding="utf-8")):
            posts.append({**post, "external": True})

    if errors:
        sys.exit("Cannot build posts.js:\n  " + "\n  ".join(errors))

    return sorted(posts, key=lambda p: (p["date"], p["title"]), reverse=True)


def render(posts):
    body = json.dumps(posts, indent=2, ensure_ascii=False)
    return f"{HEADER}window.POSTS = {body};\n"


def main():
    content = render(collect())
    current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""

    if "--check" in sys.argv:
        if content != current:
            sys.exit("posts.js is out of date — run: python3 scripts/build_posts.py")
        print("posts.js is up to date")
        return

    if content == current:
        print("posts.js is already up to date")
        return
    OUTPUT.write_text(content, encoding="utf-8")
    print(f"Wrote {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
